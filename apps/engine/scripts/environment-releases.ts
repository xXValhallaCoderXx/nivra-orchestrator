import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { ReleaseData } from "../src/environment/releases.ts";
import { compareVersions, versionParts } from "../src/environment/versions.ts";

/**
 * Regenerates Nivra's release index (NIV-55): src/environment/release-data.ts, from nodejs.org's release list and the
 * npm registry's public metadata for npm and pnpm. Run it deliberately, then review the result as data:
 *
 *   node scripts/environment-releases.ts           prints what it would write
 *   node scripts/environment-releases.ts --write   writes the file
 *
 * Only stable releases are kept: Node from 4.0.0, npm and pnpm from 7.0.0. Each source's SHA-256 is recorded with the
 * time it was fetched. Advisories are kept by hand in src/environment/advisories.ts, which this never touches. Nothing
 * here is sent anywhere, and the engine itself never fetches these.
 */

const SOURCES = {
  node: "https://nodejs.org/dist/index.json",
  npm: "https://registry.npmjs.org/npm",
  pnpm: "https://registry.npmjs.org/pnpm",
} as const;
const OUT = fileURLToPath(new URL("../src/environment/release-data.ts", import.meta.url));
const STABLE = /^\d+\.\d+\.\d+$/;

async function fetched(url: string): Promise<{ body: Buffer; sha256: string }> {
  // The registry's abbreviated metadata carries each version's engines and deprecation, and is a fraction of the size.
  const response = await fetch(url, { headers: { accept: url.startsWith("https://registry.npmjs.org/") ? "application/vnd.npm.install-v1+json" : "application/json" }, signal: AbortSignal.timeout(60_000) });
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  const body = Buffer.from(await response.arrayBuffer());
  return { body, sha256: createHash("sha256").update(body).digest("hex") };
}

const newestFirst = <T extends readonly [string, ...unknown[]]>(rows: T[]): T[] => rows.sort((a, b) => compareVersions(b[0], a[0]));

function nodeRows(body: Buffer): ReleaseData["node"] {
  const list = JSON.parse(body.toString("utf8")) as Array<{ version: string; npm?: string; lts: string | false }>;
  const rows = list
    .map((entry) => [entry.version.replace(/^v/, ""), entry.npm && STABLE.test(entry.npm) ? entry.npm : null, typeof entry.lts === "string" ? entry.lts : null] as const)
    .filter(([version]) => STABLE.test(version) && versionParts(version)![0] >= 4);
  return newestFirst([...rows]);
}

function managerRows(body: Buffer): ReleaseData["npm"] {
  const document = JSON.parse(body.toString("utf8")) as { versions: Record<string, { engines?: unknown; deprecated?: unknown }> };
  const rows = Object.entries(document.versions)
    .filter(([version]) => STABLE.test(version) && versionParts(version)![0] >= 7)
    .map(([version, meta]) => {
      const engines = meta.engines && typeof meta.engines === "object" && !Array.isArray(meta.engines) ? (meta.engines as Record<string, unknown>) : {};
      const node = typeof engines["node"] === "string" ? engines["node"].slice(0, 200) : null;
      return [version, node, typeof meta.deprecated === "string" && meta.deprecated.length > 0] as const;
    });
  return newestFirst([...rows]);
}

const line = (row: readonly unknown[]) => `    ${JSON.stringify(row)},`;

async function main() {
  const [node, npm, pnpm] = await Promise.all([fetched(SOURCES.node), fetched(SOURCES.npm), fetched(SOURCES.pnpm)]);
  const data: ReleaseData = {
    fetchedAt: new Date().toISOString(),
    sources: [
      { url: SOURCES.node, sha256: node.sha256 },
      { url: SOURCES.npm, sha256: npm.sha256 },
      { url: SOURCES.pnpm, sha256: pnpm.sha256 },
    ],
    node: nodeRows(node.body),
    npm: managerRows(npm.body),
    pnpm: managerRows(pnpm.body),
  };
  const text = [
    `import type { ReleaseData } from "./releases.ts";`,
    ``,
    `/**`,
    ` * Generated by scripts/environment-releases.ts on ${data.fetchedAt}.`,
    ` * Don't edit it by hand: run the script again, and review the result as data. Rows are newest first.`,
    ` */`,
    `export const RELEASE_DATA: ReleaseData = {`,
    `  fetchedAt: ${JSON.stringify(data.fetchedAt)},`,
    `  sources: [`,
    ...data.sources.map((source) => `    ${JSON.stringify(source)},`),
    `  ],`,
    `  node: [`,
    ...data.node.map(line),
    `  ],`,
    `  npm: [`,
    ...data.npm.map(line),
    `  ],`,
    `  pnpm: [`,
    ...data.pnpm.map(line),
    `  ],`,
    `};`,
    ``,
  ].join("\n");
  const summary = `node ${data.node.length} (newest ${data.node[0]?.[0]}), npm ${data.npm.length} (newest ${data.npm[0]?.[0]}), pnpm ${data.pnpm.length} (newest ${data.pnpm[0]?.[0]})`;
  if (process.argv.includes("--write")) {
    writeFileSync(OUT, text);
    console.log(`Wrote ${OUT}: ${summary}.`);
  } else {
    console.log(`Would write ${OUT} (${text.length} bytes): ${summary}. Run with --write to write it.`);
  }
}

await main();
